#!/usr/bin/env python3
"""Build a single-page index of course lecture materials, grouped by school.

Reads courses.json, fetches each offering's public calendar with the parser
it names, and writes _site/index.html with links back to the originals.
Nothing from the courses is copied except titles and URLs.

Usage: python3 build.py [--out _site]
"""

import argparse
import html
import json
import re
import sys
import urllib.request
from datetime import date, datetime, timezone
from pathlib import Path
from urllib.parse import urljoin

ROOT = Path(__file__).parent

TAG_RE = re.compile(r"<[^>]+>")
LINK_RE = re.compile(r"<a\s+href=\"?([^\"\s>]+)\"?[^>]*>(.*?)</a>", re.S)


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "course-notes-index/1.0"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode("utf-8", "replace")


def text(fragment):
    return html.unescape(TAG_RE.sub("", fragment)).strip()


def links(fragment, base):
    return [
        {"title": text(t), "url": urljoin(base, html.unescape(u))}
        for u, t in LINK_RE.findall(fragment)
        if text(t)
    ]


# ------------------------------------------------------------------ parsers
#
# A parser takes (page_html, base_url) and returns a list of lectures:
#   {"date": "YYYY-MM-DD", "topic": str, "topic_links": [link],
#    "materials": [link], "due": [{"title", "url", "date"}]}
# where link = {"title": str, "url": str}. Add new formats to PARSERS.

def parse_uw_createcal(page, base):
    """UW CSE calendars generated by createcal (cs.washington.edu courses)."""
    day_re = re.compile(r"<td class='eventtd' id='(\d{4}-\d{2}-\d{2})'.*?</td>", re.S)
    event_re = re.compile(r"<div class='(lecture|hw)'>(.*?)</div>", re.S)

    def span(cls, block):
        m = re.search(rf"<span class='{cls}'>(.*?)</span>(?=<br|\s*$)", block, re.S)
        return m.group(1) if m else ""

    def split_items(fragment):
        items = []
        for part in re.split(r",\s*(?![^<]*</a>)", fragment):
            found = links(part, base)
            if len(found) == 1:
                # Keep surrounding words, e.g. "<a>Reading 1</a> response".
                items.append({"title": text(part), "url": found[0]["url"]})
            elif found:
                items.extend(found)
            elif text(part):
                items.append({"title": text(part), "url": None})
        return items

    lectures, due = [], []
    for day in day_re.finditer(page):
        iso = day.group(1)
        for kind, raw in event_re.findall(day.group(0)):
            block = re.sub(r"<span class='visually-hidden'>.*?</span>", "", raw)
            if kind == "lecture":
                desc = span("description", block)
                lectures.append({
                    "date": iso,
                    "topic": text(desc),
                    "topic_links": links(desc, base),
                    "materials": links(span("materials", block), base),
                    "due": [],
                })
            else:
                due.append((iso, split_items(span("summary", block))))
    # Attach each assignment to the most recent lecture on or before its date.
    for iso, items in due:
        earlier = [l for l in lectures if l["date"] <= iso]
        target = earlier[-1] if earlier else (lectures[0] if lectures else None)
        if target is not None:
            target["due"].extend({**i, "date": iso} for i in items)
    return lectures


PARSERS = {
    "uw-createcal": parse_uw_createcal,
}


def add_unlinked(lectures, dirs):
    """Attach files from directory listings that no calendar entry links to."""
    linked = {l["url"] for lec in lectures for l in lec["materials"] + lec["topic_links"]}
    for d in dirs:
        try:
            listing = fetch(d["url"])
        except Exception as e:  # listing may disappear; the calendar is the source of truth
            print(f"    skipping {d['url']}: {e}", file=sys.stderr)
            continue
        for name in re.findall(r'href="([^"?/][^"]*)"', listing):
            m = re.match(d["pattern"], name)
            full = urljoin(d["url"], name)
            week = int(m.group(1)) if m else 0
            if m and full not in linked and 1 <= week <= len(lectures):
                title = re.sub(r"^\d+-|\.html$", "", name).replace("-", " ")
                lectures[week - 1]["materials"].append(
                    {"title": f"Notes: {title} (not linked from calendar)", "url": full})
                print(f"    added unlinked {name} to week {week}", file=sys.stderr)


def load_offering(o):
    parser = PARSERS.get(o["parser"])
    if parser is None:
        raise ValueError(f"unknown parser {o['parser']!r}; known: {', '.join(PARSERS)}")
    lectures = parser(fetch(o["calendar"]), o["calendar"])
    if not lectures:
        raise ValueError("no lectures parsed; the calendar format may have changed")
    add_unlinked(lectures, o.get("dirs", []))
    return lectures


# ---------------------------------------------------------------- rendering

def esc(s):
    return html.escape(s or "", quote=True)


def kind_of(link):
    t, u = link["title"].lower(), link["url"].lower()
    if "notes" in t:
        return "notes"
    if "whiteboard" in t:
        return "board"
    if "slide" in t or "docs.google.com/presentation" in u:
        return "slides"
    if "reading" in t or u.endswith(".pdf"):
        return "paper"
    return "link"


def fmt_date(iso, with_year=False):
    return date.fromisoformat(iso).strftime("%b %-d, %Y" if with_year else "%b %-d")


def render_cell(label, lec, today):
    head = f'<span class="olabel">{esc(label)}</span>'
    if lec is None:
        return f'<div class="cell empty">{head}<span class="muted">No lecture this week</span></div>'
    upcoming = lec["date"] > today
    seen = {m["url"] for m in lec["materials"]}
    mats = lec["materials"] + [l for l in lec["topic_links"] if l["url"] not in seen]
    chips = "".join(
        f'<a class="chip {kind_of(m)}" href="{esc(m["url"])}">{esc(m["title"])}</a>' for m in mats
    ) or f'<span class="muted">{"Not yet posted" if upcoming else "No materials linked"}</span>'
    due = ""
    if lec["due"]:
        items = "".join(
            f'<li><time>{fmt_date(i["date"])}</time> '
            + (f'<a href="{esc(i["url"])}">{esc(i["title"])}</a>' if i["url"] else esc(i["title"]))
            + "</li>"
            for i in lec["due"]
        )
        due = (f'<details class="due"><summary>Due this week ({len(lec["due"])})</summary>'
               f'<ul>{items}</ul></details>')
    return (f'<div class="cell{" upcoming" if upcoming else ""}">{head}'
            f'<time class="date">{fmt_date(lec["date"], True)}{" · upcoming" if upcoming else ""}</time>'
            f'<p class="topic">{esc(lec["topic"])}</p><div class="chips">{chips}</div>{due}</div>')


def render_course(school, course, today):
    offs = course["offerings"]
    links_html = " · ".join(
        f'<a href="{esc(o["home"])}">{esc(o["label"])}</a> '
        f'(<a href="{esc(o["calendar"])}">calendar</a>)'
        for o in offs
    )
    errors = "".join(
        f'<p class="error">Couldn\'t load {esc(o["label"])}: {esc(o["error"])}</p>'
        for o in offs if o.get("error")
    )
    ok = [o for o in offs if not o.get("error")]
    summaries = course.get("summaries", {})
    weeks = max((len(o["lectures"]) for o in ok), default=0)
    rows = []
    for w in range(weeks):
        cells = "".join(
            render_cell(o["label"], o["lectures"][w] if w < len(o["lectures"]) else None, today)
            for o in ok
        )
        note = summaries.get(str(w + 1), "").strip()
        search = " ".join(
            [course["code"], course["title"], school["name"], note]
            + [o["lectures"][w]["topic"] for o in ok if w < len(o["lectures"])]
        ).lower()
        anchor = f'{course["id"]}-week-{w + 1}'
        rows.append(
            f'<section class="week" id="{anchor}" data-search="{esc(search)}">'
            f'<h4><a href="#{anchor}">Week {w + 1}</a></h4>'
            + (f'<p class="summary">{esc(note)}</p>' if note else "")
            + f'<div class="grid" style="--cols:{len(ok)}">{cells}</div></section>'
        )
    return (f'<article class="course" id="{esc(course["id"])}">'
            f'<header class="course-head"><h3>{esc(course["code"])}: {esc(course["title"])}</h3>'
            f'<p class="muted">{links_html}</p></header>{errors}{"".join(rows)}</article>')


def render(config, generated):
    today = generated.date().isoformat()
    toc, body = [], []
    for school in config["schools"]:
        toc.append(
            f'<li><a href="#{esc(school["id"])}">{esc(school["name"])}</a><ul>'
            + "".join(
                f'<li><a href="#{esc(c["id"])}">{esc(c["code"])}: {esc(c["title"])}</a></li>'
                for c in school["courses"]
            )
            + "</ul></li>"
        )
        body.append(
            f'<section class="school" id="{esc(school["id"])}"><h2>{esc(school["name"])}</h2>'
            + "".join(render_course(school, c, today) for c in school["courses"])
            + "</section>"
        )
    n_courses = sum(len(s["courses"]) for s in config["schools"])
    template = (ROOT / "template.html").read_text()
    return (template
            .replace("{{TOC}}", "".join(toc))
            .replace("{{BODY}}", "\n".join(body))
            .replace("{{COUNTS}}", f'{n_courses} course{"s" * (n_courses != 1)} from '
                     f'{len(config["schools"])} school{"s" * (len(config["schools"]) != 1)}')
            .replace("{{GENERATED}}", generated.strftime("%Y-%m-%d %H:%M UTC")))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="_site")
    args = ap.parse_args()

    config = json.loads((ROOT / "courses.json").read_text())
    loaded = failed = 0
    for school in config["schools"]:
        for course in school["courses"]:
            print(f"{course['code']} ({school['name']})", file=sys.stderr)
            path = ROOT / "summaries" / f"{course['id']}.json"
            course["summaries"] = json.loads(path.read_text()) if path.exists() else {}
            for o in course["offerings"]:
                try:
                    o["lectures"] = load_offering(o)
                    print(f"  {o['label']}: {len(o['lectures'])} lectures", file=sys.stderr)
                    loaded += 1
                except Exception as e:
                    o["error"] = str(e)
                    print(f"  {o['label']}: FAILED: {e}", file=sys.stderr)
                    failed += 1
    if not loaded:
        sys.exit("no offerings loaded")

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "index.html").write_text(render(config, datetime.now(timezone.utc)))
    (out / "data.json").write_text(json.dumps(config, indent=2))
    print(f"wrote {out / 'index.html'} ({loaded} offerings, {failed} failed)", file=sys.stderr)


if __name__ == "__main__":
    main()
